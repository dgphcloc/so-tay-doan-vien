-- 1. Phạm vi nộp của nhiệm vụ: 'assigned' (chỉ đoàn viên chi đoàn được giao) | 'open' (ai cũng tham gia)
alter table public.tasks
  add column if not exists submit_scope text not null default 'assigned';
alter table public.tasks
  drop constraint if exists tasks_submit_scope_check;
alter table public.tasks
  add constraint tasks_submit_scope_check check (submit_scope in ('assigned', 'open'));

-- 2. Bảng bài nộp CÁ NHÂN của đoàn viên (tách khỏi task_results là bài của chi đoàn)
create table if not exists public.member_submissions (
  id            bigint generated by default as identity primary key,
  task_id       bigint not null references public.tasks(id) on delete cascade,
  member_id     bigint not null references public.members(id) on delete cascade,
  unit_id       bigint not null references public.units(id) on delete restrict,
  note          text,
  lat           double precision,
  lng           double precision,
  status        public.review_status not null default 'pending',
  submitted_at  timestamptz not null default now(),
  reviewed_by   bigint references public.members(id) on delete set null,
  reviewed_at   timestamptz,
  review_note   text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint member_submissions_task_member_uq unique (task_id, member_id),
  constraint member_submissions_lat_check check (lat is null or (lat >= -90 and lat <= 90)),
  constraint member_submissions_lng_check check (lng is null or (lng >= -180 and lng <= 180))
);
create index if not exists member_submissions_task_idx on public.member_submissions (task_id);
create index if not exists member_submissions_unit_idx on public.member_submissions (unit_id);
create index if not exists member_submissions_member_idx on public.member_submissions (member_id);

-- 3. Ảnh minh chứng cá nhân: dùng cột submission_id của evidences? Không — evidences.submission_id trỏ criterion_submissions.
--    Thêm cột riêng member_submission_id cho ảnh của bài nộp cá nhân.
alter table public.evidences
  add column if not exists member_submission_id bigint references public.member_submissions(id) on delete cascade;
create index if not exists evidences_member_submission_idx on public.evidences (member_submission_id);

-- Ràng buộc cũ evidences_one_target chỉ cho đúng 1 trong (task_id, submission_id).
-- Mở rộng: đúng 1 trong 3 đích (nhiệm vụ chi đoàn / tiêu chí / bài nộp cá nhân).
alter table public.evidences drop constraint if exists evidences_one_target;
alter table public.evidences
  add constraint evidences_one_target
  check (num_nonnulls(task_id, submission_id, member_submission_id) = 1);

-- 4. RLS
alter table public.member_submissions enable row level security;

drop policy if exists member_submissions_select on public.member_submissions;
create policy member_submissions_select on public.member_submissions
  for select to authenticated
  using (
    private.is_admin()
    or member_id = private.my_member_id()
    or (private.my_role() = 'unit_secretary' and unit_id = private.my_unit_id())
  );

-- Đoàn viên chỉ nộp cho chính mình, đúng chi đoàn của mình, vào nhiệm vụ đang mở
-- và đúng phạm vi (assigned: chi đoàn được giao; open: ai cũng nộp được), luôn ở trạng thái 'pending'.
drop policy if exists member_submissions_insert on public.member_submissions;
create policy member_submissions_insert on public.member_submissions
  for insert to authenticated
  with check (
    member_id = private.my_member_id()
    and unit_id = private.my_unit_id()
    and status = 'pending'
    and exists (
      select 1 from public.tasks t
      where t.id = member_submissions.task_id
        and t.status = 'published'
        and (
          t.submit_scope = 'open'
          or exists (
            select 1 from public.task_units tu
            where tu.task_id = t.id and tu.unit_id = member_submissions.unit_id
          )
        )
    )
  );

-- Duyệt: admin hoặc bí thư đúng chi đoàn. Đoàn viên chỉ sửa bài của mình khi chưa được duyệt
-- và chỉ được đưa về 'pending' (nộp lại) — không tự duyệt được.
drop policy if exists member_submissions_update on public.member_submissions;
create policy member_submissions_update on public.member_submissions
  for update to authenticated
  using (
    private.is_admin()
    or (private.my_role() = 'unit_secretary' and unit_id = private.my_unit_id())
    or (member_id = private.my_member_id() and status in ('pending', 'rejected'))
  )
  with check (
    private.is_admin()
    or (private.my_role() = 'unit_secretary' and unit_id = private.my_unit_id())
    or (member_id = private.my_member_id() and status = 'pending')
  );

-- 5. Cho đoàn viên đọc được nhiệm vụ (tasks + task_units) để thấy việc cần nộp
drop policy if exists tasks_select_member on public.tasks;
create policy tasks_select_member on public.tasks
  for select to authenticated
  using (private.my_role() is not null and status = 'published');

drop policy if exists task_units_select_member on public.task_units;
create policy task_units_select_member on public.task_units
  for select to authenticated
  using (private.my_role() is not null);

