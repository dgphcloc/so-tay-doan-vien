-- 1. Bảng hoạt động sổ tay
create table if not exists public.journal_entries (
  id            bigint generated by default as identity primary key,
  profile_id    uuid not null references public.profiles (id) on delete cascade,
  title         text not null check (btrim(title) <> ''),
  activity_date date not null default current_date,
  note          text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists journal_entries_profile_idx on public.journal_entries (profile_id, activity_date desc);

-- 2. Ảnh của hoạt động (tối đa 10, kiểm ở client; DB giữ đơn giản)
create table if not exists public.journal_images (
  id               bigint generated by default as identity primary key,
  entry_id         bigint not null references public.journal_entries (id) on delete cascade,
  profile_id       uuid not null references public.profiles (id) on delete cascade,
  storage_path     text not null,
  url              text not null,
  file_name        text,
  created_at       timestamptz not null default now()
);
create index if not exists journal_images_entry_idx on public.journal_images (entry_id);
create index if not exists journal_images_profile_idx on public.journal_images (profile_id);

-- 3. Link của hoạt động (nhiều link, mỗi link có ghi chú riêng)
create table if not exists public.journal_links (
  id         bigint generated by default as identity primary key,
  entry_id   bigint not null references public.journal_entries (id) on delete cascade,
  profile_id uuid not null references public.profiles (id) on delete cascade,
  url        text not null,
  note       text,
  created_at timestamptz not null default now()
);
create index if not exists journal_links_entry_idx on public.journal_links (entry_id);
create index if not exists journal_links_profile_idx on public.journal_links (profile_id);

-- 4. RLS — CHỈ CHỦ SỞ HỮU. Không có nhánh is_admin() ở bất kỳ policy nào.
alter table public.journal_entries enable row level security;
alter table public.journal_images  enable row level security;
alter table public.journal_links   enable row level security;

drop policy if exists journal_entries_own on public.journal_entries;
create policy journal_entries_own on public.journal_entries
  for all to authenticated
  using (profile_id = auth.uid())
  with check (profile_id = auth.uid());

drop policy if exists journal_images_own on public.journal_images;
create policy journal_images_own on public.journal_images
  for all to authenticated
  using (profile_id = auth.uid())
  with check (profile_id = auth.uid());

drop policy if exists journal_links_own on public.journal_links;
create policy journal_links_own on public.journal_links
  for all to authenticated
  using (profile_id = auth.uid())
  with check (profile_id = auth.uid());

-- 5. Storage: ảnh sổ tay nằm trong bucket 'evidences', thư mục journal_<uid>/
--    Policy đọc công khai của bucket đã có, nhưng tên file chứa uuid ngẫu nhiên
--    và người khác không biết đường dẫn. Ghi/xóa phải đúng thư mục của mình.
drop policy if exists journal_storage_insert on storage.objects;
create policy journal_storage_insert on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'evidences'
    and (storage.foldername(name))[1] = 'journal_' || auth.uid()::text
  );

drop policy if exists journal_storage_delete on storage.objects;
create policy journal_storage_delete on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'evidences'
    and (storage.foldername(name))[1] = 'journal_' || auth.uid()::text
  );

-- 6. Đếm kiểm tra
select
  (select count(*) from public.journal_entries) as so_hoat_dong,
  (select count(*) from public.journal_images)  as so_anh,
  (select count(*) from public.journal_links)   as so_link;
