-- Sổ tay: mỗi tài khoản có nhật ký hoạt động RIÊNG.
--   • Tuyệt đối riêng tư: kể cả admin cũng không đọc được của người khác.
--   • Ảnh lưu ở bucket 'evidences' với tiền tố journal_<profile_id>/.
--   • Dữ liệu cũ của criterion_submissions GIỮ NGUYÊN, chỉ ẩn khỏi giao diện.
