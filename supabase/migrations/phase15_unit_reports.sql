-- =====================================================================
-- GIAI ĐOẠN 15 · BÁO CÁO RIÊNG CỦA BÍ THƯ CHI ĐOÀN
--
-- BỐI CẢNH NGHIỆP VỤ:
--   Đã có `task_results` = KẾT QUẢ TỔNG HỢP của chi đoàn cho một nhiệm vụ
--   (số người tham gia, kết quả đạt được). Bí thư chi đoàn nộp thay chi đoàn.
--
--   Nhưng trách nhiệm của bí thư NẶNG HƠN đoàn viên thường: họ còn phải chỉ
--   đạo, phân công, xử lý khó khăn, đề xuất. Phần đó không có chỗ ghi nhận.
--
--   -> Thêm bảng `unit_reports`: BÁO CÁO RIÊNG của bí thư/phó bí thư chi đoàn
--      về quá trình tổ chức thực hiện nhiệm vụ.
--
--   HAI THỨ NÀY ĐỘC LẬP, CÙNG TỒN TẠI:
--     • task_results  = chi đoàn đã làm được gì (kết quả)
--     • unit_reports  = bí thư đã chỉ đạo thế nào (báo cáo)
--
-- Quy tắc:
--   • UNIQUE(task_id, unit_id) — mỗi chi đoàn 1 báo cáo / nhiệm vụ
--   • Có duyệt: pending -> approved / rejected + review_note (như member_submissions)
--   • Nội dung: ghi chú + ảnh/tệp/link, tái dùng bảng `evidences`
--   • Phó bí thư nộp được, ghi rõ ai nộp (submitted_by)
--
-- Chạy trên Supabase SQL Editor. An toàn khi chạy lại (idempotent).
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. BẢNG unit_reports
-- ---------------------------------------------------------------------
create table if not exists public.unit_reports (
  id           bigint generated by default as identity primary key,
  task_id      bigint not null references public.tasks(id) on delete cascade,
  unit_id      bigint not null references public.units(id) on delete restrict,
  submitted_by bigint not null references public.members(id) on delete restrict,
  note         text,
  status       text not null default 'pending',
  submitted_at timestamptz not null default now(),
  reviewed_by  bigint references public.members(id) on delete set null,
  reviewed_at  timestamptz,
  review_note  text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- UNIQUE: mỗi chi đoàn chỉ 1 báo cáo cho mỗi nhiệm vụ
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'unit_reports_task_unit_uq'
  ) then
    alter table public.unit_reports
      add constraint unit_reports_task_unit_uq unique (task_id, unit_id);
  end if;

  if not exists (
    select 1 from pg_constraint where conname = 'unit_reports_status_chk'
  ) then
    alter table public.unit_reports
      add constraint unit_reports_status_chk
      check (status in ('pending', 'approved', 'rejected'));
  end if;
end $$;

create index if not exists unit_reports_task_idx   on public.unit_reports (task_id);
create index if not exists unit_reports_unit_idx   on public.unit_reports (unit_id);
create index if not exists unit_reports_status_idx on public.unit_reports (status);

comment on table public.unit_reports is
  'Báo cáo riêng của Bí thư/Phó Bí thư chi đoàn về quá trình chỉ đạo thực hiện nhiệm vụ. Độc lập với task_results (kết quả tổng hợp của chi đoàn).';
comment on column public.unit_reports.submitted_by is
  'Người nộp báo cáo (bí thư hoặc phó bí thư chi đoàn).';
comment on column public.unit_reports.note is
  'Nội dung báo cáo: công tác chỉ đạo, phân công, khó khăn, đề xuất.';

-- ---------------------------------------------------------------------
-- 2. MINH CHỨNG CỦA BÁO CÁO — thêm cột vào bảng evidences
-- ---------------------------------------------------------------------
alter table public.evidences
  add column if not exists unit_report_id bigint;
create index if not exists evidences_unit_report_idx on public.evidences (unit_report_id);

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'evidences_unit_report_fk'
  ) then
    alter table public.evidences
      add constraint evidences_unit_report_fk
      foreign key (unit_report_id) references public.unit_reports(id) on delete cascade;
  end if;
end $$;

-- QUAN TRỌNG: constraint cũ chỉ cho đúng 1 trong 3 đích. Phải mở rộng thành
-- 4 đích, nếu không insert minh chứng của báo cáo sẽ bị từ chối vì
-- num_nonnulls(task_id, submission_id, member_submission_id) = 0.
alter table public.evidences drop constraint if exists evidences_one_target;
alter table public.evidences
  add constraint evidences_one_target
  check (num_nonnulls(task_id, submission_id, member_submission_id, unit_report_id) = 1);

-- ---------------------------------------------------------------------
-- 3. RLS
-- ---------------------------------------------------------------------
alter table public.unit_reports enable row level security;

-- SELECT: admin/staff thấy tất cả; đoàn viên thấy báo cáo của chi đoàn mình
drop policy if exists unit_reports_select on public.unit_reports;
create policy unit_reports_select on public.unit_reports
  for select to authenticated
  using (
    private.is_admin()
    or private.my_role() = 'staff'
    or unit_id = private.my_unit_id()
  );

-- INSERT: chỉ bí thư/phó bí thư của chính chi đoàn đó, và chi đoàn phải
--         nằm trong danh sách được giao nhiệm vụ. Admin nộp hộ được.
drop policy if exists unit_reports_insert on public.unit_reports;
create policy unit_reports_insert on public.unit_reports
  for insert to authenticated
  with check (
    private.is_admin()
    or (
      private.is_unit_secretary()
      and unit_id = private.my_unit_id()
      and submitted_by = private.my_member_id()
      and exists (
        select 1 from public.task_units tu
        where tu.task_id = unit_reports.task_id
          and tu.unit_id = unit_reports.unit_id
      )
    )
  );

-- UPDATE: admin/staff duyệt; bí thư chi đoàn sửa báo cáo của mình khi
--         chưa được duyệt (pending / rejected) và chỉ được đưa về 'pending'.
drop policy if exists unit_reports_update on public.unit_reports;
create policy unit_reports_update on public.unit_reports
  for update to authenticated
  using (
    private.is_admin()
    or private.my_role() = 'staff'
    or (
      private.is_unit_secretary()
      and unit_id = private.my_unit_id()
      and status in ('pending', 'rejected')
    )
  )
  with check (
    private.is_admin()
    or private.my_role() = 'staff'
    or (
      private.is_unit_secretary()
      and unit_id = private.my_unit_id()
      and status = 'pending'
    )
  );

-- DELETE: chỉ admin
drop policy if exists unit_reports_delete on public.unit_reports;
create policy unit_reports_delete on public.unit_reports
  for delete to authenticated
  using (private.is_admin());

-- ---------------------------------------------------------------------
-- 4. MINH CHỨNG CỦA BÁO CÁO — ai đọc được?
--
--    Policy `evidences_select` (phase14b) đã cho admin/staff/chủ sở hữu/bí thư
--    đơn vị mình. Nhưng đoàn viên THƯỜNG trong cùng chi đoàn thì chưa đọc được
--    minh chứng do bí thư nộp. Bổ sung đúng phạm vi: chỉ minh chứng gắn với
--    báo cáo của chi đoàn mình (không mở rộng sang bài nộp cá nhân của người khác).
-- ---------------------------------------------------------------------
drop policy if exists evidences_select_unit_report on public.evidences;
create policy evidences_select_unit_report on public.evidences
  for select to authenticated
  using (
    unit_report_id is not null
    and exists (
      select 1 from public.unit_reports ur
      where ur.id = evidences.unit_report_id
        and ur.unit_id = private.my_unit_id()
    )
  );

commit;

-- =====================================================================
