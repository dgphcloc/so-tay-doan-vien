-- =====================================================================
select 'bang_unit_reports' as muc, count(*) as so_luong
from information_schema.tables
where table_schema = 'public' and table_name = 'unit_reports';

select 'policy_unit_reports' as muc, policyname, cmd
from pg_policies
where schemaname = 'public' and tablename = 'unit_reports'
order by policyname;

-- Phải thấy 4 đích trong constraint (task_id, submission_id, member_submission_id, unit_report_id)
select pg_get_constraintdef(oid) as dinh_nghia
from pg_constraint
where conname = 'evidences_one_target';

select 'cot_unit_report_id' as muc, count(*) as so_luong
from information_schema.columns
where table_schema = 'public' and table_name = 'evidences' and column_name = 'unit_report_id';